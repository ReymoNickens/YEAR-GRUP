/**
 * Bundle every migration (and optional extra files, such as a provisioned
 * organisation) into one SQL file to paste into the Supabase SQL editor.
 *   node scripts/setup-sql.mjs <out.sql> [extra.sql ...]
 * It runs as one transaction and records each migration in Supabase's own
 * migration history, so `supabase migration list` and the dashboard agree.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const [out, ...extras] = process.argv.slice(2);
if (!out) { console.error("Usage: setup-sql.mjs <out.sql> [extra.sql ...]"); process.exit(2); }
const dir = "supabase/migrations";
const parts = ["-- Year Group Hub: full database setup. Paste into Supabase → SQL editor → Run.", "-- Generated by scripts/setup-sql.mjs. Do not edit by hand.", "begin;", ""];
// Extras named like migrations (a timestamp first) slot in by name, as they do in the tests;
// any other extra (a provisioned organisation) goes at the end.
const timed = (f) => /^\d{14}_/.test(basename(f));
const ordered = [
  ...readdirSync(dir).filter((f) => f.endsWith(".sql")).map((f) => ({ path: join(dir, f), migration: true })),
  ...extras.filter(timed).map((f) => ({ path: f, migration: false })),
].sort((a, b) => basename(a.path).localeCompare(basename(b.path)));
for (const { path, migration } of ordered) {
  parts.push(`-- ===== ${basename(path)} =====`, readFileSync(path, "utf8"), "");
  if (migration) {
    const [version, ...rest] = basename(path).replace(/\.sql$/, "").split("_");
    parts.push(`insert into supabase_migrations.schema_migrations (version, name) values ('${version}', '${rest.join("_")}') on conflict do nothing;`, "");
  }
}
for (const extra of extras.filter((f) => !timed(f))) parts.push(`-- ===== ${extra} =====`, readFileSync(extra, "utf8"), "");
parts.push("commit;", "");
writeFileSync(out, parts.join("\n"));
console.log(`Wrote ${out}`);
